import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { mkdir } from 'node:fs/promises'
const browser = await chromium.launch({ executablePath: process.env.TTF_BROWSER_PATH ?? 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true })
const base = process.env.TTF_TEST_URL ?? 'http://127.0.0.1:5173/'
await mkdir('output/internal-interactions', { recursive: true })
try {
  for (const width of [1440, 390, 320]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, reducedMotion: 'reduce', hasTouch: width < 700, isMobile: width < 700 })
    await context.addInitScript(() => sessionStorage.setItem('ttf-intro-seen', '1'))
    const page = await context.newPage(), errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(`${base}#culture`)
    const flow = page.locator('.culture-map-browser')
    await flow.getByRole('button', { name: '下一张地图' }).click()
    const selectedTitle = await flow.locator('.atlas-flow-card[aria-pressed=true]').getAttribute('aria-label')
    const open = flow.locator('.atlas-controls').last().getByRole('button')
    if (width < 700) await open.tap(); else await open.click()
    const reader = page.getByRole('dialog')
    await reader.waitFor()
    assert.equal(await reader.locator('h2').innerText(), selectedTitle)
    assert.ok(await reader.getByTestId('map-viewport').locator('img').first().getAttribute('src'))
    await page.getByTestId('lightbox-close').click()
    await page.locator('#culture').evaluate(node => { node.scrollTop = 0 })
    assert.ok(await page.locator('#culture').evaluate(node => node.scrollWidth <= node.clientWidth + 1))
    await page.screenshot({ path: `output/internal-interactions/culture-${width}.png` })
    await page.goto(`${base}#contest`)
    const tabs = page.getByRole('tab')
    await tabs.first().waitFor()
    const total = await page.locator('#contest-results article').count()
    await tabs.getByText('第二届', { exact: true }).click()
    assert.equal(await page.getByRole('tabpanel').locator('article').count(), 1)
    assert.ok((await page.getByRole('tabpanel').innerText()).includes('第二届'))
    assert.equal((await page.locator('.journal-filter button[aria-pressed=true]').innerText()).replace(/\s/g, ''), '第二届2')
    assert.equal(await page.locator('#contest-results article').count(), 2)
    assert.equal(await page.locator('.contest-winner').count(), 1)
    await page.getByRole('tab', { name: '第二届', exact: true }).press('ArrowRight')
    assert.equal(await page.getByRole('tab', { name: '第三届', exact: true }).getAttribute('aria-selected'), 'true')
    await page.locator('.journal-filter button').first().click()
    assert.equal(await tabs.first().getAttribute('aria-selected'), 'true')
    assert.equal(await page.locator('#contest-results article').count(), total)
    assert.ok(await page.getByRole('tabpanel').evaluate(node => node.querySelector('.atlas-panel-reading').getBoundingClientRect().bottom <= node.getBoundingClientRect().bottom + 1), 'All edition records must remain visible without clipping')
    await page.locator('.contest-editions').scrollIntoViewIfNeeded()
    assert.ok(await page.locator('#contest').evaluate(node => node.scrollWidth <= node.clientWidth + 1))
    await page.screenshot({ path: `output/internal-interactions/contest-${width}.png` })
    await page.keyboard.press('Control+Shift+A')
    const gate = page.getByRole('dialog', { name: '天图府 · 账号' })
    await gate.getByLabel('登录邮箱', { exact: true }).fill('reves')
    await gate.getByLabel('登录密码', { exact: true }).fill('LOCAL-DEMO-ONLY-1')
    await gate.getByTestId('account-login-submit').click()
    await gate.waitFor({ state: 'hidden' })
    await page.getByRole('tab', { name: '第二届', exact: true }).click()
    const year = page.getByRole('tabpanel').getByRole('textbox').nth(1)
    await year.fill('2026 年 · 测试')
    await page.getByRole('tab', { name: '第一届', exact: true }).click()
    assert.equal(await page.getByRole('tabpanel').getByRole('textbox').nth(1).inputValue(), '20XX 年')
    await page.getByRole('tab', { name: '第二届', exact: true }).click()
    assert.equal(await page.getByRole('tabpanel').getByRole('textbox').nth(1).inputValue(), '2026 年 · 测试')
    assert.deepEqual(errors, [])
    console.log(`PASS ${width}px: culture original-image reader; edition tabs/filter/winners; keyboard and original editing paths.`)
    await context.close()
  }
} finally { await browser.close() }
